"""Golden tests: hand-written input rows -> exact expected document.

The expected documents are written by hand (not generated by the transformer),
so a transformer bug can't hide by appearing on both sides of a comparison."""
import json
from pathlib import Path

import pytest
from bson import json_util

from migrator.transform.documents import build_document

GOLDEN = sorted((Path(__file__).parent / "golden").glob("*.json"))


def _norm(doc):
    """Compare via canonical Extended JSON (tz-aware vs naive datetimes compare equal)."""
    return json.loads(json_util.dumps(doc, json_options=json_util.CANONICAL_JSON_OPTIONS))


@pytest.mark.parametrize("path", GOLDEN, ids=[p.stem for p in GOLDEN])
def test_golden(mapping, path):
    case = json.loads(path.read_text())
    inp = case["input"]
    lookups = {t: {int(k): v for k, v in rows.items()} for t, rows in inp["lookups"].items()}
    got = build_document(mapping, inp["collection"], inp["row"], lookups, inp["children"], inp["joins"])
    expected = json_util.loads(json.dumps(case["expected"]))
    assert _norm(got) == _norm(expected)
    assert list(got) == list(expected), "field order differs"
