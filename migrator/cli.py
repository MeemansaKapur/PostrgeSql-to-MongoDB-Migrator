import logging
import sys

import typer
import yaml

from migrator.config import get_settings, load_mapping

app = typer.Typer(help="PostgreSQL → MongoDB online migrator", no_args_is_help=True)

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)-5s %(name)s: %(message)s",
                    datefmt="%H:%M:%S")


def _mapping(path: str):
    from migrator.transform.mapping import Mapping
    return Mapping.from_dict(load_mapping(path))


def _mongo():
    from pymongo import MongoClient
    s = get_settings()
    # short server selection so transient outages surface fast and get retried by us
    return MongoClient(s.mongo_uri, tz_aware=True, serverSelectionTimeoutMS=5000)[s.mongo_db]


@app.command()
def propose(
    output: str = typer.Option("-", "--output", "-o", help="file to write, '-' for stdout"),
    embed_max: int = typer.Option(100, help="max children per parent to embed"),
    lookup_max: int = typer.Option(1000, help="max rows for a lookup table"),
    ignore: list[str] = typer.Option(["canary"], help="tables to leave out"),
):
    """Read the PostgreSQL schema and propose a mapping (review it, then save as mapping.yaml)."""
    import psycopg

    from migrator.schema.introspect import introspect
    from migrator.schema.propose import propose as do_propose

    with psycopg.connect(get_settings().pg_dsn) as conn:
        cat = introspect(conn)
    mapping = do_propose(cat, set(ignore), embed_max, lookup_max)
    text = "# Generated by `migrator propose`. Review before use.\n" + \
        yaml.safe_dump(mapping, sort_keys=False, width=110)
    if output == "-":
        sys.stdout.write(text)
    else:
        with open(output, "w") as f:
            f.write(text)
        typer.echo(f"wrote {output}", err=True)


@app.command()
def bulk(
    mapping: str = typer.Option("mapping.yaml", help="approved mapping"),
    batch_size: int = typer.Option(2000, help="rows per batch"),
    collection: list[str] = typer.Option(None, "--collection", "-c", help="only these collections"),
    restart: bool = typer.Option(False, help="ignore checkpoints and copy from the start"),
    indexes: bool = typer.Option(True, help="build secondary indexes after the copy"),
):
    """Copy existing rows into MongoDB with checkpoints."""
    import time

    import psycopg

    from migrator.bulk.copier import BulkCopier, reset_checkpoints
    from migrator.indexes import ensure_indexes

    m, db = _mapping(mapping), _mongo()
    if restart:
        reset_checkpoints(db)
    t0 = time.perf_counter()
    with psycopg.connect(get_settings().pg_dsn, autocommit=True) as pg:
        results = BulkCopier(pg, db, m, batch_size).run(collection or None)
    copy_secs = time.perf_counter() - t0
    if indexes:
        t1 = time.perf_counter()
        names = ensure_indexes(db)
        typer.echo(f"indexes: {len(names)} ensured in {time.perf_counter() - t1:.1f}s")
    total = sum(r["rows"] + r["child_rows"] for r in results)
    typer.echo(f"bulk copy: {total:,} rows read (join rows count once per side) -> "
               f"{sum(r['rows'] for r in results):,} documents in {copy_secs:.1f}s "
               f"({total / max(copy_secs, 1e-9):,.0f} rows/s)")


@app.command()
def indexes(unique_only: bool = typer.Option(False, help="only the unique indexes (before sync)")):
    """Create target indexes."""
    from migrator.indexes import ensure_indexes
    typer.echo("\n".join(ensure_indexes(_mongo(), secondary=not unique_only)))


@app.command()
def sync(
    mapping: str = typer.Option("mapping.yaml", help="approved mapping"),
    batch_size: int = typer.Option(500, help="max events per batch"),
    group_id: str = typer.Option("migrator-sync", help="Kafka consumer group"),
    exit_when_idle: float = typer.Option(None, help="stop after N idle seconds (tests/cutover)"),
    lag_csv: str = typer.Option("results/lag_samples.csv", help="canary lag samples output"),
):
    """Replay Debezium change events from Kafka into MongoDB."""
    from migrator.cdc.consumer import SyncConsumer
    from migrator.indexes import ensure_indexes

    s = get_settings()
    db = _mongo()
    ensure_indexes(db, secondary=False)   # unique indexes before any CDC write
    SyncConsumer(_mapping(mapping), db, s.kafka_bootstrap, s.pg_dsn, group_id, batch_size,
                 lag_csv).run(max_idle_s=exit_when_idle)


@app.command()
def connector(action: str = typer.Argument("status", help="register | status | delete"),
              config: str = typer.Option("connect/register-postgres.json")):
    """Manage the Debezium connector (step 1: start capturing before the bulk copy)."""
    import json
    import urllib.request

    base = get_settings().connect_url
    cfg = json.load(open(config))
    name = cfg["name"]
    if action == "register":
        req = urllib.request.Request(f"{base}/connectors", data=json.dumps(cfg).encode(),
                                     headers={"Content-Type": "application/json"}, method="POST")
    elif action == "delete":
        req = urllib.request.Request(f"{base}/connectors/{name}", method="DELETE")
    else:
        req = urllib.request.Request(f"{base}/connectors/{name}/status")
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            typer.echo(r.read().decode() or f"{action}: ok")
    except urllib.error.HTTPError as e:
        typer.echo(f"{e.code}: {e.read().decode()}", err=True)
        raise typer.Exit(1)


@app.command()
def verify(
    mapping: str = typer.Option("mapping.yaml", help="approved mapping"),
    watch: bool = typer.Option(False, help="keep checking (counts 30 s, samples 5 min) and alert"),
    full: bool = typer.Option(False, help="full chunked checksum of every document (use at cutover)"),
    sample_size: int = typer.Option(500, help="random ids per collection for the deep check"),
    count_every: float = typer.Option(30, help="--watch: seconds between count checks"),
    report: str = typer.Option(None, help="write the JSON report here"),
):
    """Counts, sampled checks, checksums, lag and alerts. Exit code 1 on any mismatch."""
    import json

    import psycopg

    from migrator.verify.checksum import full_checksum
    from migrator.verify.counts import count_checks, stubs
    from migrator.verify.run import Verifier
    from migrator.verify.sample import sample_check

    s, m, db = get_settings(), _mapping(mapping), _mongo()
    with psycopg.connect(s.pg_dsn, autocommit=True) as pg:
        if watch:
            Verifier(pg, db, m, s.kafka_bootstrap, sample_size).watch(count_every)
            return
        v = Verifier(pg, db, m, s.kafka_bootstrap, sample_size)
        out = {"lag": v.lag_checks(), "counts": count_checks(pg, db, m), "stubs": stubs(db, m)}
        failed = any(c["diff"] for c in out["counts"])
        typer.echo(f"\nlag: canary p95={out['lag']['sync'].get('canary_p95_ms')} ms, "
                   f"kafka behind={out['lag']['kafka']['messages_behind']}, "
                   f"dlq={out['lag']['sync'].get('dlq_count')}")
        typer.echo(f"\n{'count check':<45}{'postgres':>10}{'mongo':>10}{'diff':>7}")
        for c in out["counts"]:
            typer.echo(f"{c['check']:<45}{c['pg']:>10,}{c['mongo']:>10,}{c['diff']:>+7}")
        typer.echo(f"stub documents: {sum(len(x) for x in out['stubs'].values())}")
        if full:
            out["checksum"] = full_checksum(pg, db, m)
            docs = sum(r["documents"] for r in out["checksum"])
            mism = sum(len(r["mismatches"]) for r in out["checksum"])
            failed |= mism > 0
            typer.echo(f"\nfull checksum: {docs:,} documents, {mism} mismatches")
            for r in out["checksum"]:
                for x in r["mismatches"][:5]:
                    typer.echo(f"  {r['collection']} _id={x['_id']}: {x['fields']}")
        else:
            out["sample"] = sample_check(pg, db, m, sample_size)
            n = sum(r["existing_rows"] for r in out["sample"])
            mism = sum(len(r["mismatches"]) for r in out["sample"])
            failed |= mism > 0
            typer.echo(f"\nsampled: {n:,} documents, {mism} mismatches")
            for r in out["sample"]:
                for x in r["mismatches"][:5]:
                    typer.echo(f"  {r['collection']} _id={x['_id']}: {x['fields']}")
        if report:
            with open(report, "w") as f:
                json.dump(out, f, indent=2, default=str)
        typer.echo("\nRESULT: " + ("MISMATCH" if failed else "OK"))
        raise typer.Exit(1 if failed else 0)


@app.command()
def bench(
    runs: int = typer.Option(200, help="measured runs per query per repetition"),
    warmup: int = typer.Option(20, help="discarded warm-up runs"),
    reps: int = typer.Option(3, help="repetitions; the median one is reported"),
    out_dir: str = typer.Option("results", help="where to write bench.csv / bench_raw.csv / bench.md"),
):
    """Run the 6 benchmark queries on both databases."""
    from pathlib import Path

    import psycopg

    from migrator.bench.run import check_equivalence, markdown, run

    with psycopg.connect(get_settings().pg_dsn, autocommit=True) as pg:
        db = _mongo()
        eq = check_equivalence(pg, db)
        typer.echo(f"answer equivalence: {eq}")
        if "DIFFERENT" in eq.values():
            typer.echo("engines disagree; fix before timing", err=True)
            raise typer.Exit(1)
        summary = run(pg, db, runs, warmup, reps, out_dir)
    md = markdown(summary)
    Path(out_dir, "bench.md").write_text(md + "\n")
    typer.echo(md)


@app.command("bench-profile")
def bench_profile(
    runs: int = typer.Option(200), warmup: int = typer.Option(20), reps: int = typer.Option(3),
    label: str = typer.Option("localhost", help="describes the network conditions of this run"),
    out_dir: str = typer.Option("results"),
):
    """Q7 full customer profile: 3 PostgreSQL strategies vs MongoDB."""
    import random
    from pathlib import Path

    import psycopg

    from migrator.bench import profile

    with psycopg.connect(get_settings().pg_dsn, autocommit=True) as pg:
        db = _mongo()
        from functools import partial
        import json as _json
        from decimal import Decimal
        from psycopg.types.json import set_json_loads
        set_json_loads(partial(_json.loads, parse_float=Decimal), pg)
        max_c = pg.execute("SELECT MAX(customer_id) FROM customers").fetchone()[0]
        sample = random.Random(3).sample(range(1, max_c + 1), 300)
        bad = profile.check_equivalence(pg, db, sample)
        typer.echo(f"equivalence: {300 - len(bad)}/300 customers identical across all 4 variants")
        if bad:
            typer.echo(f"differ: {bad[:10]}", err=True)
            raise typer.Exit(1)
        rows = profile.run(pg, db, runs, warmup, reps, out_dir, label=label)
    md = profile.markdown(rows)
    with open(Path(out_dir, "bench_profile.md"), "a") as f:
        f.write(md + "\n\n")
    typer.echo(md)


